-- LAVÉA schema for the existing dashboard.js
-- Review this SQL before running it in Supabase SQL Editor.
-- Assumes only trusted salon administrators are created in Supabase Auth.

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  price numeric(10,2) not null default 0 check (price >= 0),
  duration integer not null default 30 check (duration > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  service text not null,
  booking_date date not null,
  booking_time time not null,
  notes text,
  status text not null default 'Pending'
    check (status in ('Pending','Confirmed','Cancelled','Completed')),
  created_at timestamptz not null default now()
);

alter table public.services enable row level security;
alter table public.bookings enable row level security;

-- Public visitors may view the service menu; only signed-in admins may change it.
drop policy if exists "Public can view services" on public.services;
create policy "Public can view services" on public.services
  for select to anon, authenticated using (true);

drop policy if exists "Admins manage services" on public.services;
create policy "Admins manage services" on public.services
  for all to authenticated using (true) with check (true);

-- Public visitors can submit booking requests, but cannot read customer bookings.
drop policy if exists "Public can submit pending bookings" on public.bookings;
create policy "Public can submit pending bookings" on public.bookings
  for insert to anon, authenticated
  with check (status = 'Pending');

drop policy if exists "Admins view bookings" on public.bookings;
create policy "Admins view bookings" on public.bookings
  for select to authenticated using (true);

drop policy if exists "Admins update bookings" on public.bookings;
create policy "Admins update bookings" on public.bookings
  for update to authenticated using (true) with check (true);

grant select on public.services to anon, authenticated;
grant insert, update, delete on public.services to authenticated;
grant select, update on public.bookings to authenticated;
grant insert on public.bookings to anon, authenticated;

grant usage, select on all sequences in schema public to authenticated;

